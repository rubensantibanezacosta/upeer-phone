import { describe, expect, it } from 'vitest';
import { ed25519 } from '@noble/curves/ed25519.js';
import { bytesToHex, hexToBytes, utf8ToBytes } from '@noble/hashes/utils.js';

import { canonicalStringify } from './canonical-json';
import vectors from '../../transport-bridge/testdata/dht_vectors.json';

type SignedPacketVector = {
  name: string;
  packet: Record<string, unknown>;
  canonical: string;
  signature: string;
};

type LocationVector = {
  name: string;
  signedData: unknown;
  canonical: string;
  signature: string;
};

type CanonicalVector = {
  name: string;
  payload: unknown;
  canonical: string;
  signature: string;
};

type DhtVectorFixture = {
  generatedBy: string;
  identity: { secretKeySeed: string; publicKey: string; upeerId: string; address: string; };
  canonicalVectors: CanonicalVector[];
  signedPackets: SignedPacketVector[];
  locationBlocks: LocationVector[];
};

const fixture = vectors as unknown as DhtVectorFixture;
const seed = hexToBytes(fixture.identity.secretKeySeed);
const publicKey = hexToBytes(fixture.identity.publicKey);

function sign(payload: string): string {
  return bytesToHex(ed25519.sign(utf8ToBytes(payload), seed));
}

function verify(payload: string, signature: string): boolean {
  return ed25519.verify(hexToBytes(signature), utf8ToBytes(payload), publicKey);
}

describe('Desktop DHT canonical vectors', () => {
  it('uses vectors generated by the desktop implementation', () => {
    expect(fixture.generatedBy).toBe('upper-desktop');
    expect(fixture.canonicalVectors.length).toBeGreaterThan(0);
    expect(fixture.signedPackets.length).toBe(12);
    expect(fixture.locationBlocks.length).toBe(3);
    expect(bytesToHex(ed25519.getPublicKey(seed))).toBe(fixture.identity.publicKey);
  });

  it('matches canonical bytes and signatures for nested, Unicode and escaped values', () => {
    for (const vector of fixture.canonicalVectors) {
      const canonical = canonicalStringify(vector.payload);
      expect(canonical, vector.name).toBe(vector.canonical);
      expect(sign(canonical), vector.name).toBe(vector.signature);
      expect(verify(vector.canonical, vector.signature), vector.name).toBe(true);
    }
  });

  it('keeps desktop key ordering based on UTF-16 code units', () => {
    const vector = fixture.canonicalVectors.find((candidate) => candidate.name === 'utf16-key-order');
    expect(vector?.canonical).toBe('{"a":3,"z":5,"á":4,"😀":1,"\ue000":2}');
  });

  it('verifies every signed DHT packet and excludes only top-level signature fields', () => {
    for (const vector of fixture.signedPackets) {
      const packet = { ...vector.packet };
      delete packet.signature;
      delete packet.contactCache;
      delete packet.renewalToken;
      const canonical = canonicalStringify(packet);
      expect(canonical, vector.name).toBe(vector.canonical);
      expect(sign(canonical), vector.name).toBe(vector.signature);
      expect(verify(canonical, vector.signature), vector.name).toBe(true);
      expect(packet.senderUpeerId, vector.name).toBe(fixture.identity.upeerId);
      expect(packet.senderYggAddress, vector.name).toBe(fixture.identity.address);
    }
  });

  it('verifies multi-address, device metadata and legacy location blocks', () => {
    for (const vector of fixture.locationBlocks) {
      const canonical = canonicalStringify(vector.signedData);
      expect(canonical, vector.name).toBe(vector.canonical);
      expect(sign(canonical), vector.name).toBe(vector.signature);
      expect(verify(vector.canonical, vector.signature), vector.name).toBe(true);
    }
  });

  it('rejects a tampered signed packet', () => {
    const vector = fixture.signedPackets[0];
    const packet: Record<string, unknown> = { ...vector.packet };
    packet.queryId = 'tampered';
    delete packet.signature;
    delete packet.contactCache;
    delete packet.renewalToken;
    expect(verify(canonicalStringify(packet), vector.signature)).toBe(false);
  });
});
