const ALL_EMOJIS = EMOJI_GROUPS.flatMap((group) => group.emojis);

export function emojisForGroup(groupId: string): string[] {
  return EMOJI_GROUPS.find((group) => group.id === groupId)?.emojis ?? [];
}

export function searchEmojis(query: string): string[] {
  const term = query.trim().toLowerCase();
  if (!term) return [];
  const matchedGroups = EMOJI_GROUPS.filter((group) => group.label.toLowerCase().includes(term));
  if (matchedGroups.length > 0) return matchedGroups.flatMap((group) => group.emojis);
  return ALL_EMOJIS.filter((emoji) => emoji.includes(term));
}

export function pushRecentEmoji(recent: string[], emoji: string): string[] {
  return [emoji, ...recent.filter((item) => item !== emoji)].slice(0, RECENT_EMOJI_LIMIT);
}
